def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    engine_root = Path(args.engine_root).resolve()

    project_name = args.name if (args.name != "mock_test" or not args.simulate_ai_burst) else "test_ai_burst"
    workspace = (
        Path(args.workspace).resolve()
        if args.workspace
        else engine_root / "mock_workspace" / project_name
    )

    if args.simulate_ai_burst:
        return run_simulate_ai_burst(
            engine_root=engine_root,
            project_name=project_name,
            workspace=workspace,
            json_output=args.json,
        )

    summary: dict = {
        "project":      args.name,
        "workspace":    str(workspace),
        "engine_root":  str(engine_root),
        "bursts":       args.bursts,
        "start_ts":     datetime.now(timezone.utc).isoformat(),
        "events_in_db": None,
        "worker_pid":   None,
        "stopped":      False,
    }

    # ------------------------------------------------------------------
    # Step 1 – Scaffold workspace
    # ------------------------------------------------------------------
    print(f"\n[MOCK] Scaffolding workspace at: {workspace}")
    scaffold_workspace(workspace)

    if args.workspace_only:
        print("[MOCK] --workspace-only flag set. Exiting after scaffold.")
        if args.json:
            print(json.dumps(summary, indent=2))
        return 0

    # ------------------------------------------------------------------
    # Step 2 – Start worker
    # ------------------------------------------------------------------
    sup = Supervisor(engine_root)
    print(f"[MOCK] Starting worker for project '{args.name}' …")

    try:
        result = sup.start_project(
            name=args.name,
            path=str(workspace),
            scaffold=True,
        )
    except ValueError as exc:
        print(f"[MOCK][ERROR] {exc}", file=sys.stderr)
        return 1

    summary["worker_pid"] = result["pid"]
    print(f"[MOCK] Worker started | PID={result['pid']}")

    # Give the worker time to emit its startup heartbeat
    print("[MOCK] Waiting 1.5s for worker startup heartbeat …")
    time.sleep(1.5)

    # ------------------------------------------------------------------
    # Step 3 – Edit bursts
    # ------------------------------------------------------------------
    print(f"\n[MOCK] Simulating {args.bursts} edit burst(s) "
          f"with {args.burst_delay}s delay between them …")

    for i in range(1, args.bursts + 1):
        files = simulate_edit_burst(workspace, iteration=i)
        print(f"  Burst {i}/{args.bursts}: modified {len(files)} file(s)")
        if i < args.bursts:
            time.sleep(args.burst_delay)

    # ------------------------------------------------------------------
    # Step 4 – Report status
    # ------------------------------------------------------------------
    time.sleep(0.5)  # let the last heartbeat arrive
    statuses = sup.get_status(args.name)
    if statuses:
        s = statuses[0]
        print(
            f"\n[MOCK] Worker status | alive={s['alive']} | "
            f"uptime={s['uptime_s']:.1f}s | "
            f"heartbeat_age={s['last_heartbeat_s']:.1f}s | "
            f"memory={s.get('memory_mb')} MB"
        )

    # ------------------------------------------------------------------
    # Step 5 – (Optional) Stop worker and archive
    # ------------------------------------------------------------------
    if args.no_stop:
        print(
            f"\n[MOCK] --no-stop flag set. Worker (PID {result['pid']}) "
            "is still running.\n"
            f"  Stop it with:  python start.py stop --project {args.name}"
        )
    else:
        print(f"\n[MOCK] Stopping worker for '{args.name}' …")
        stop_result = sup.stop_project(args.name)
        summary["stopped"] = True
        print(
            f"[MOCK] Worker stopped | exit_code={stop_result['exit_code']}"
        )

    # ------------------------------------------------------------------
    # Step 6 – Count DB events (post-archive, look in last_run)
    # ------------------------------------------------------------------
    event_count = _count_events(engine_root, args.name)
    summary["events_in_db"] = event_count
    summary["end_ts"] = datetime.now(timezone.utc).isoformat()

    if args.json:
        print("\n" + json.dumps(summary, indent=2))
    else:
        print("\n" + "-" * 60)
        print("  MOCK ACTIVITY SUMMARY")
        print("-" * 60)
        print(f"  Project      : {summary['project']}")
        print(f"  Workspace    : {summary['workspace']}")
        print(f"  Worker PID   : {summary['worker_pid']}")
        print(f"  Bursts run   : {args.bursts}")
        print(f"  Events in DB : {event_count if event_count >= 0 else 'N/A'}")
        print(f"  Worker stopped: {summary['stopped']}")
        print("-" * 60 + "\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
