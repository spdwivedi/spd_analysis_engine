_MAIN_PY_TEMPLATE = '''\
"""
main.py – generated by SPD mock_activity.py
Iteration: {iteration}  |  Generated: {ts}
"""

from utils import greet, compute


def main() -> None:
    """Entry point."""
    name = "SPD Engine"
    result = compute({a}, {b})
    print(greet(name))
    print(f"compute({a}, {b}) = {{result}}")


if __name__ == "__main__":
    main()
'''

_UTILS_PY_TEMPLATE = '''\
"""
utils.py – generated by SPD mock_activity.py
Iteration: {iteration}  |  Generated: {ts}
"""

import math


def greet(name: str) -> str:
    """Return a friendly greeting."""
    return f"Hello from {{name}}! (mock session iteration {iteration})"


def compute(x: float, y: float) -> float:
    """Perform a dummy computation."""
    return round(math.sqrt(abs(x ** 2 + y ** 2 + {noise})), 4)


def _internal_helper(data: list) -> list:
    """Filter and transform data."""
    return [item for item in data if isinstance(item, (int, float))]
'''


def _rand_int(lo: int = 1, hi: int = 100) -> int:
    return random.randint(lo, hi)


def _rand_noise() -> float:
    return round(random.uniform(0.0, 99.99), 4)


def scaffold_workspace(workspace: Path) -> None:
    """
    Create (or refresh) the dummy workspace with ``main.py`` and ``utils.py``.

    The files are given meaningful Python content so a real watchdog observer
    would record genuine EDIT events.

    Parameters
    ----------
    workspace : Directory that will contain the generated files.
    """
    workspace.mkdir(parents=True, exist_ok=True)

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    a, b = _rand_int(), _rand_int()

    main_content = _MAIN_PY_TEMPLATE.format(
        iteration=0, ts=ts, a=a, b=b
    )
    utils_content = _UTILS_PY_TEMPLATE.format(
        iteration=0, ts=ts, noise=_rand_noise()
    )

    (workspace / "main.py").write_text(main_content, encoding="utf-8")
    (workspace / "utils.py").write_text(utils_content, encoding="utf-8")
    (workspace / "README.md").write_text(
        f"# Mock Workspace\n\nGenerated at {ts} by SPD mock_activity.py\n",
        encoding="utf-8",
    )
    logger.info("Workspace scaffolded at: %s", workspace)


def simulate_edit_burst(workspace: Path, iteration: int) -> list[str]:
    """
    Simulate a burst of file edits and return the list of modified paths.

    Each burst rewrites ``main.py`` and ``utils.py`` with new random values
    to ensure the content (and therefore file modification time) changes.

    Parameters
    ----------
    workspace : Directory containing the files.
    iteration : Burst counter (embedded in generated content for traceability).

    Returns
    -------
    list[str] – Paths of files that were written.
    """
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    a, b = _rand_int(), _rand_int()
    noise = _rand_noise()
    modified: list[str] = []

    main_path = workspace / "main.py"
    main_path.write_text(
        _MAIN_PY_TEMPLATE.format(iteration=iteration, ts=ts, a=a, b=b),
        encoding="utf-8",
    )
    modified.append(str(main_path))

    utils_path = workspace / "utils.py"
    utils_path.write_text(
        _UTILS_PY_TEMPLATE.format(iteration=iteration, ts=ts, noise=noise),
        encoding="utf-8",
    )
    modified.append(str(utils_path))

    # Occasionally create a new ephemeral file to test CREATE events
    if random.random() < 0.4:
        rand_name = "".join(random.choices(string.ascii_lowercase, k=6))
        ephemeral = workspace / f"tmp_{rand_name}.py"
        ephemeral.write_text(
            f"# Ephemeral file – burst {iteration}\nDATA = {_rand_int()}\n",
            encoding="utf-8",
        )
        modified.append(str(ephemeral))

    logger.info("Burst #%s: wrote %d files", iteration, len(modified))
    return modified


# ---------------------------------------------------------------------------
# Session DB query helpers (used in post-test summary)
# ---------------------------------------------------------------------------

def _count_events(engine_root: Path, project_name: str) -> int:
    """Count events recorded in the project's current session DB."""
    rotator = StorageRotator(engine_root)
    db_path = rotator.current_path(project_name) / "session.db"
    if not db_path.exists():
        # Try last_run if current already got archived
        db_path = rotator.last_run_path(project_name) / "session.db"
    if not db_path.exists():
        return -1
    try:
        with SessionDB(db_path) as db:
            assert db._conn is not None
            cur = db._conn.execute("SELECT COUNT(*) FROM events")
            return cur.fetchone()[0]
    except Exception as exc:  # noqa: BLE001
        logger.warning("Could not count events: %s", exc)
        return -1


