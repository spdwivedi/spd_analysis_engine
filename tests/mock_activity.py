"""
tests/mock_activity.py
======================
Standalone CLI utility to generate a realistic dummy workspace and simulate
file-system activity for integration testing of the SPD Analysis Engine.

What it does
------------
1. Creates a temporary workspace with two Python source files:
   ``main.py`` and ``utils.py``.
2. (Optionally) Starts a project worker via the Supervisor API and waits for
   it to emit a startup heartbeat.
3. Simulates a configurable number of timed edit bursts by writing randomised
   content changes to the workspace files.
4. Reports heartbeat counts and session DB event counts at the end.
5. Stops the worker cleanly and prints a final summary.

Usage
-----
::

    # Scaffold a workspace, start a worker, run 5 edit bursts, stop:
    python tests/mock_activity.py --name demo --bursts 5

    # Only create the workspace (no worker):
    python tests/mock_activity.py --name demo --workspace-only

    # Keep the worker running after the test (manual stop):
    python tests/mock_activity.py --name demo --no-stop

Options
-------
--name          Project name  (default: mock_test)
--workspace     Path for the dummy workspace  (default: <engine_root>/mock_workspace/<name>)
--bursts        Number of edit bursts to simulate  (default: 3)
--burst-delay   Seconds to wait between bursts  (default: 2.5)
--workspace-only  Only create workspace files; do not start a worker
--no-stop       Leave the worker running after the test completes
--engine-root   Override engine root  (default: parent of tests/)
--json          Print final summary as JSON
"""

